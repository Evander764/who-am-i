// 18 张宿舍整改照片对应的步骤标注
// 文件名格式：public/images/dorm/01.jpg ... 18.jpg
export type Frame = {
  id: number;        // 1 ~ 18
  src: string;       // 静态路径
  step: string;      // STEP 01 / 04 / ...
  caption: string;   // 一句话
};

const CAPTIONS = [
  "测量 · 先把一团乱变成可以计算的尺寸",
  "采购 · 工具、板材、收纳件，按需求下单",
  "拆解 · 旧东西先拆开，才知道能怎么改",
  "归类 · 分区、整理、扔掉多余的东西",
  "改造 · 第一件新东西落到它该在的位置",
  "打孔 · 上墙的第一颗钉子，位置不能凭感觉",
  "组装 · 把图纸里的家具慢慢变成实物",
  "走线 · 让插座和线缆长在顺手的位置",
  "调试 · 灯光、桌面、坐姿，一遍一遍试",
  "贴合 · 让墙面、家具和人的动线不打架",
  "微调 · 第二天起床，又发现还能再改一点",
  "成形 · 房间开始像一个人真正住在里面",
  "添置 · 只补真的会用到的小东西",
  "去多余 · 把好看但没必要的部分拿走",
  "灯光 · 暖一点、可调一点、不刺眼",
  "桌面 · 留出给正在做的事使用的空地",
  "床位 · 睡得着，比拍照好看更重要",
  "完工 · 终于可以坐下来，看会儿书",
];

export const frames: Frame[] = Array.from({ length: 18 }, (_, i) => {
  const id = i + 1;
  return {
    id,
    src: `/images/dorm/${String(id).padStart(2, "0")}.jpg`,
    step: `STEP ${String(id).padStart(2, "0")} / 18`,
    caption: CAPTIONS[i] ?? "继续整理中",
  };
});
